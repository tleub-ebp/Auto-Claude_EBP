"""Materialising resolved skills into every enabled harness.

One authored skill in ``skills/`` becomes N files on disk. This module is the
only thing that writes them; nothing else should ever hand-edit the outputs.

**Ownership.** The build owns exactly the paths it emitted last time, recorded
in ``skills-lock.json``. Anything else on disk is left alone. That matters
right now: ``.agents/skills/`` still holds 76 hand-committed BMAD directories
and ``.gemini/commands/`` 77 hand-committed TOML files. Until BMAD becomes a
pack, a build must not touch them — a generator that owns a whole directory
would delete them on its first run.

**Provenance.** Each emitted file carries the pack, the pack version and a
content hash in its frontmatter, and the same triple lands in the lockfile.
Nothing changes without a visible lockfile diff, which is the mechanism that
keeps an upstream release from silently rewriting a pinned skill.
"""

from __future__ import annotations

import hashlib
import json
import logging
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from .agents import collect_registry_agents, emit_for_harness
from .harnesses import load_harnesses
from .packs import SkillSource
from .resolver import Resolution

__all__ = ["BuildPlan", "BuildResult", "plan_build", "apply_build", "LOCKFILE_RELPATH"]

logger = logging.getLogger(__name__)

LOCKFILE_RELPATH = Path("skills-lock.json")
LOCK_VERSION = 1

_GENERATED_NOTE = (
    "Generated by `pnpm run skills:build` from {source}. Do not edit here — "
    "edit the source and rebuild."
)


@dataclass
class BuildPlan:
    """Every file the build wants on disk, as path -> content."""

    files: dict[Path, str] = field(default_factory=dict)
    """Text files, relative to the repo root."""
    copies: dict[Path, Path] = field(default_factory=dict)
    """Bundled resources: destination (relative) -> absolute source."""
    warnings: list[str] = field(default_factory=list)
    """Advisory, never fatal — things the build did that someone should see."""

    def all_paths(self) -> set[Path]:
        return set(self.files) | set(self.copies)


@dataclass
class BuildResult:
    written: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)
    unchanged: list[Path] = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return bool(self.written or self.removed)


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def content_hash(src: SkillSource) -> str:
    """A stable hash over everything that travels with the skill.

    Covers the SKILL.md plus every bundled file (scripts, references,
    templates), so a change to a helper script shows up as a lockfile diff the
    same way a change to the instructions does.
    """
    h = hashlib.sha256()
    if src.kind == "agent":
        h.update(src.path.read_bytes())
        return h.hexdigest()
    for f in sorted(p for p in src.dir.rglob("*") if p.is_file()):
        h.update(str(f.relative_to(src.dir)).encode("utf-8"))
        h.update(_sha256_file(f).encode("ascii"))
    return h.hexdigest()


def _render_frontmatter(meta: dict[str, Any]) -> str:
    """Emit YAML frontmatter with `name` and `description` first.

    Field order is not cosmetic: every harness reads those two, and several
    truncate long descriptions, so they must not be buried under metadata.
    """
    ordered: dict[str, Any] = {}
    for key in ("name", "description", "when_to_use", "paths"):
        if key in meta:
            ordered[key] = meta[key]
    for key, value in meta.items():
        if key not in ordered:
            ordered[key] = value
    return yaml.safe_dump(
        ordered,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=10_000,
    )


def _emit_document(
    src: SkillSource, pack_version: str, digest: str, source_rel: str
) -> str:
    """Rebuild a SKILL.md / agent file with derived provenance injected."""
    meta = dict(src.meta)
    container = (
        dict(meta.get("metadata") or {})
        if isinstance(meta.get("metadata"), dict)
        else {}
    )
    wp = (
        dict(container.get("workpilot") or {})
        if isinstance(container.get("workpilot"), dict)
        else {}
    )

    # Derived, never authored by hand — that is why they can't drift.
    wp["pack"] = src.pack
    wp["version"] = pack_version
    wp["content_sha256"] = digest
    if src.targets:
        wp["targets"] = src.targets

    container["workpilot"] = wp
    meta["metadata"] = container

    # The provenance note goes *inside* the frontmatter, as a YAML comment.
    # In the body it would be the first thing the model reads on every single
    # invocation -- pure token cost for a message aimed at humans. Here the
    # frontmatter parser strips it along with the rest of the block.
    note = _GENERATED_NOTE.format(source=source_rel)
    return f"---\n# {note}\n{_render_frontmatter(meta)}---\n\n{src.body.rstrip()}\n"


def _toml_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _emit_gemini_command(src: SkillSource, body: str) -> str:
    description = str(src.meta.get("description", "") or "").replace("\n", " ").strip()
    return (
        f'description = "{_toml_escape(description)}"\n'
        f'prompt = """\n{body.rstrip()}\n"""\n'
    )


def _marketplace(resolution: Resolution) -> str:
    packs = sorted(resolution.packs.values(), key=lambda p: p.name)
    doc = {
        "name": "workpilot",
        "owner": {"name": "WorkPilot AI Team"},
        "plugins": [
            {
                "name": f"workpilot-{p.name}",
                "source": f"./skills/{p.name}",
                "version": p.version,
                "description": p.description,
            }
            for p in packs
        ],
    }
    return json.dumps(doc, indent="\t", ensure_ascii=False) + "\n"


def plan_build(
    source_root: Path,
    resolution: Resolution,
    harness_names: list[str] | None = None,
) -> BuildPlan:
    """Compute every output file without touching the filesystem."""
    matrix = load_harnesses(source_root)
    if harness_names:
        unknown = [h for h in harness_names if h not in matrix]
        if unknown:
            raise ValueError(f"unknown harness(es): {', '.join(unknown)}")
        enabled = [matrix[h] for h in harness_names]
    else:
        enabled = [h for h in matrix.values() if h.default]

    plan = BuildPlan()
    digests = {s.name: content_hash(s) for s in resolution.selected}

    for src in resolution.selected:
        pack_version = resolution.packs[src.pack].version
        # Relative, so the output is byte-identical on every machine --
        # otherwise `skills:check` would fail in CI on the path alone.
        source_rel = src.path.relative_to(source_root).as_posix()
        document = _emit_document(src, pack_version, digests[src.name], source_rel)

        for harness in enabled:
            if src.kind == "skill":
                if not harness.skills_path:
                    continue
                base = Path(harness.skills_path) / src.name
                plan.files[base / "SKILL.md"] = document
                # Bundled resources travel with the skill.
                for extra in sorted(p for p in src.dir.rglob("*") if p.is_file()):
                    if extra.name == "SKILL.md" and extra.parent == src.dir:
                        continue
                    plan.copies[base / extra.relative_to(src.dir)] = extra
                if harness.format == "toml-command" and harness.commands_path:
                    plan.files[Path(harness.commands_path) / f"{src.name}.toml"] = (
                        _emit_gemini_command(src, src.body)
                    )
            else:
                if harness.agents_path:
                    plan.files[Path(harness.agents_path) / f"{src.name}.md"] = document
                elif harness.format == "toml-command" and harness.commands_path:
                    # This harness has no subagents, so the persona cannot be
                    # dispatched to. Exposing it as a slash command is the
                    # honest degradation: the user invokes it themselves
                    # instead of the parent delegating to it.
                    plan.files[Path(harness.commands_path) / f"{src.name}.toml"] = (
                        _emit_gemini_command(src, src.body)
                    )

    # The Python subagent registry, emitted per harness from the same source.
    # Packs contribute their own `agents/` above; this is the roster the
    # pipeline itself runs, which until now existed only in Python.
    registry_agents = collect_registry_agents()
    for harness in enabled:
        emission = emit_for_harness(harness, registry_agents)
        for rel, body in emission.files.items():
            path = Path(rel)
            if path in plan.files:
                # A pack authored an agent of the same name. The pack wins:
                # it is version-controlled content someone wrote deliberately,
                # whereas the registry entry is a default.
                logger.debug("pack agent shadows registry agent at %s", rel)
                continue
            plan.files[path] = body
        plan.warnings.extend(emission.warnings())

    plan.files[Path(".claude-plugin") / "marketplace.json"] = _marketplace(resolution)
    return plan


def _lockfile(
    source_root: Path,
    out_root: Path,
    resolution: Resolution,
    plan: BuildPlan,
    harness_names: list[str],
) -> str:
    digests = {s.name: content_hash(s) for s in resolution.selected}
    # scripts/skills_sync.py records the upstream tree SHA it last observed on
    # each pack. The build owns the rest of this file, so it has to carry that
    # field forward -- dropping it would make every sync run report "moved"
    # and the signal would stop meaning anything.
    previous_packs = _previous_pack_entries(out_root)
    doc = {
        "lockfileVersion": LOCK_VERSION,
        "note": (
            "Generated by `pnpm run skills:build`. `emitted` is what the build "
            "owns: the next build removes entries that disappear from it and "
            "touches nothing else."
        ),
        "harnesses": sorted(harness_names),
        "packs": {
            name: {
                "version": pack.version,
                "source": pack.source,
                "path": pack.path.relative_to(source_root).as_posix(),
                **(
                    {"upstreamTreeSha": sha}
                    if (sha := previous_packs.get(name, {}).get("upstreamTreeSha"))
                    else {}
                ),
            }
            for name, pack in sorted(resolution.packs.items())
        },
        "skills": {
            src.name: {
                "kind": src.kind,
                "pack": src.pack,
                "packVersion": resolution.packs[src.pack].version,
                "source": src.path.relative_to(source_root).as_posix(),
                "contentSha256": digests[src.name],
                "targets": src.targets or {},
            }
            for src in sorted(resolution.selected, key=lambda s: s.name)
        },
        # Rejections are deliberately NOT recorded. They depend on what is on
        # disk right now — a vendored pack contributes rejections only after
        # `skills:bootstrap`, so writing them here would make a committed file
        # a function of transient local state and `skills:check` would fail for
        # whoever had bootstrapped. `skills:list` reports them live, which is
        # where a diagnostic belongs.
        "emitted": sorted(p.as_posix() for p in plan.all_paths()),
    }
    return json.dumps(doc, indent="\t", ensure_ascii=False) + "\n"


def _previous_pack_entries(out_root: Path) -> dict[str, dict]:
    """Pack entries from the existing lockfile, for fields the build does not own."""
    lock = out_root / LOCKFILE_RELPATH
    if not lock.is_file():
        return {}
    try:
        return json.loads(lock.read_text(encoding="utf-8")).get("packs") or {}
    except json.JSONDecodeError:
        return {}


def _owned_by(rel: Path, roots: set[str]) -> bool:
    """Whether ``rel`` belongs to one of the harness directories being built.

    The lockfile is always owned — it is rewritten every run. Anything under a
    directory no enabled harness claims is left alone, because this run has no
    opinion about it.
    """
    if rel == LOCKFILE_RELPATH:
        return True
    posix = rel.as_posix()
    return any(posix == root or posix.startswith(f"{root}/") for root in roots)


def _harness_roots(harnesses) -> set[str]:
    """Every output directory the given harnesses write into."""
    roots = {".claude-plugin"}
    for harness in harnesses:
        for path in (harness.skills_path, harness.agents_path, harness.commands_path):
            if path:
                roots.add(path.rstrip("/"))
    return roots


def _previously_emitted(out_root: Path) -> set[Path]:
    lock = out_root / LOCKFILE_RELPATH
    if not lock.is_file():
        return set()
    try:
        data = json.loads(lock.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return set()
    return {Path(p) for p in data.get("emitted", [])}


def apply_build(
    out_root: Path,
    resolution: Resolution,
    plan: BuildPlan,
    harness_names: list[str],
    *,
    source_root: Path | None = None,
    check_only: bool = False,
) -> BuildResult:
    """Write the plan to disk, or report drift when ``check_only``.

    ``out_root`` is the *consuming project*: that is where `.agents/skills/`
    and `skills-lock.json` land. ``source_root`` is the repo the packs were
    authored in, used only to make lockfile paths relative. They are the same
    directory when building WorkPilot for itself, and different when building
    a consumer project — which is the normal case, and the reason these are
    two parameters instead of one.
    """
    source_root = source_root or out_root
    result = BuildResult()
    matrix = load_harnesses(source_root)
    enabled_paths = _harness_roots(
        [matrix[h] for h in harness_names if h in matrix] or list(matrix.values())
    )

    # The lockfile is part of the output, and its `emitted` list must describe
    # the build that produced it — so compute it before deciding what to remove.
    lock_text = _lockfile(source_root, out_root, resolution, plan, harness_names)
    wanted_files = dict(plan.files)
    wanted_files[LOCKFILE_RELPATH] = lock_text

    # What the build owns and this run did not produce. Scoped to the
    # harnesses being built: `--harness=copilot` must not delete the agnostic
    # output, which is the one the backend serves. Before this, a single-
    # harness build wiped every other harness's files and reported it as
    # ordinary cleanup.
    stale = {
        rel
        for rel in _previously_emitted(out_root) - plan.all_paths()
        if _owned_by(rel, enabled_paths)
    }

    for rel, content in sorted(wanted_files.items()):
        dest = out_root / rel
        current = dest.read_text(encoding="utf-8") if dest.is_file() else None
        if current == content:
            result.unchanged.append(rel)
            continue
        result.written.append(rel)
        if not check_only:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")

    for rel, source in sorted(plan.copies.items()):
        dest = out_root / rel
        if dest.is_file() and _sha256_file(dest) == _sha256_file(source):
            result.unchanged.append(rel)
            continue
        result.written.append(rel)
        if not check_only:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, dest)

    for rel in sorted(stale):
        dest = out_root / rel
        if not dest.exists():
            continue
        result.removed.append(rel)
        if not check_only:
            dest.unlink()
            # Clean up a directory the removal just emptied.
            parent = dest.parent
            while parent != out_root and parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent

    return result
